// Minimal GitHub REST client used to push a generated zmk-config and run the
// ZMK GitHub Actions build, entirely from the browser with a personal access token.

const API = 'https://api.github.com'
const TOKEN_KEY = 'zmkc.github.token'
const REPO_KEY = 'zmkc.github.repo'

export function getToken(): string {
  try { return localStorage.getItem(TOKEN_KEY) ?? '' } catch { return '' }
}
export function setToken(t: string) {
  try { if (t) localStorage.setItem(TOKEN_KEY, t); else localStorage.removeItem(TOKEN_KEY) } catch { /* ignore */ }
}
export function getSavedRepo(layoutId: string): string {
  try { return localStorage.getItem(`${REPO_KEY}.${layoutId}`) ?? '' } catch { return '' }
}
export function setSavedRepo(layoutId: string, repo: string) {
  try { localStorage.setItem(`${REPO_KEY}.${layoutId}`, repo) } catch { /* ignore */ }
}

export class GitHubError extends Error {
  status: number
  constructor(status: number, message: string) {
    super(message)
    this.status = status
  }
}

export class GitHub {
  token: string
  constructor(token: string) {
    this.token = token
  }

  async req<T = unknown>(path: string, init: RequestInit & { json?: unknown } = {}): Promise<T> {
    const headers: Record<string, string> = {
      Accept: 'application/vnd.github+json',
      Authorization: `Bearer ${this.token}`,
      'X-GitHub-Api-Version': '2022-11-28',
    }
    let body = init.body
    if (init.json !== undefined) {
      headers['Content-Type'] = 'application/json'
      body = JSON.stringify(init.json)
    }
    const res = await fetch(path.startsWith('http') ? path : API + path, { ...init, headers, body })
    if (!res.ok) {
      let msg = res.statusText
      try {
        const j = await res.json()
        msg = j.message ?? msg
        if (j.errors) msg += ': ' + JSON.stringify(j.errors)
      } catch { /* ignore */ }
      throw new GitHubError(res.status, `${res.status} ${msg}`)
    }
    if (res.status === 204) return undefined as T
    return res.json() as Promise<T>
  }

  user() {
    return this.req<{ login: string; name?: string; avatar_url: string }>('/user')
  }

  async repos(): Promise<{ full_name: string; private: boolean; default_branch: string; pushed_at: string }[]> {
    return this.req('/user/repos?per_page=100&sort=pushed&affiliation=owner')
  }

  repo(full: string) {
    return this.req<{ full_name: string; default_branch: string; html_url: string; private: boolean }>(`/repos/${full}`)
  }

  createRepo(name: string, isPrivate: boolean) {
    return this.req<{ full_name: string; default_branch: string; html_url: string }>('/user/repos', {
      method: 'POST',
      json: { name, private: isPrivate, auto_init: true, description: 'ZMK firmware config generated by ZMK Configurator' },
    })
  }

  /** Commit a full set of files on top of `branch` (files not listed are kept). Returns the new commit sha. */
  async commitFiles(full: string, branch: string, files: Record<string, string>, message: string): Promise<string> {
    const ref = await this.req<{ object: { sha: string } }>(`/repos/${full}/git/ref/heads/${encodeURIComponent(branch)}`)
    const parentSha = ref.object.sha
    const parent = await this.req<{ tree: { sha: string } }>(`/repos/${full}/git/commits/${parentSha}`)
    const tree = await Promise.all(
      Object.entries(files).map(async ([path, content]) => {
        const blob = await this.req<{ sha: string }>(`/repos/${full}/git/blobs`, {
          method: 'POST',
          json: { content, encoding: 'utf-8' },
        })
        return { path, mode: '100644', type: 'blob', sha: blob.sha }
      }),
    )
    const newTree = await this.req<{ sha: string }>(`/repos/${full}/git/trees`, {
      method: 'POST',
      json: { base_tree: parent.tree.sha, tree },
    })
    const commit = await this.req<{ sha: string }>(`/repos/${full}/git/commits`, {
      method: 'POST',
      json: { message, tree: newTree.sha, parents: [parentSha] },
    })
    await this.req(`/repos/${full}/git/refs/heads/${encodeURIComponent(branch)}`, {
      method: 'PATCH',
      json: { sha: commit.sha },
    })
    return commit.sha
  }

  async runForCommit(full: string, sha: string) {
    const r = await this.req<{ workflow_runs: WorkflowRun[] }>(`/repos/${full}/actions/runs?head_sha=${sha}&per_page=5`)
    return r.workflow_runs[0] as WorkflowRun | undefined
  }

  run(full: string, id: number) {
    return this.req<WorkflowRun>(`/repos/${full}/actions/runs/${id}`)
  }

  async jobs(full: string, runId: number) {
    const r = await this.req<{ jobs: { name: string; status: string; conclusion: string | null; html_url: string }[] }>(
      `/repos/${full}/actions/runs/${runId}/jobs?per_page=50`,
    )
    return r.jobs
  }

  async artifacts(full: string, runId: number) {
    const r = await this.req<{ artifacts: { id: number; name: string; size_in_bytes: number; archive_download_url: string }[] }>(
      `/repos/${full}/actions/runs/${runId}/artifacts`,
    )
    return r.artifacts
  }

  /** Download an artifact zip. GitHub redirects to blob storage; may fail on CORS in some browsers. */
  async downloadArtifact(url: string): Promise<Blob> {
    const res = await fetch(url, { headers: { Authorization: `Bearer ${this.token}` } })
    if (!res.ok) throw new GitHubError(res.status, `Artifact download failed (${res.status})`)
    return res.blob()
  }

  createGist(files: Record<string, string>, description: string, isPublic: boolean) {
    return this.req<{ id: string; html_url: string; owner?: { login: string } }>('/gists', {
      method: 'POST',
      json: { description, public: isPublic, files: Object.fromEntries(Object.entries(files).map(([k, v]) => [k, { content: v }])) },
    })
  }
}

export interface WorkflowRun {
  id: number
  status: 'queued' | 'in_progress' | 'completed' | 'waiting' | 'requested' | 'pending'
  conclusion: 'success' | 'failure' | 'cancelled' | 'skipped' | 'timed_out' | null
  html_url: string
  created_at: string
}

/** Fetch a public gist's files without auth (for shared layouts). */
export async function fetchGist(id: string): Promise<Record<string, string>> {
  const res = await fetch(`${API}/gists/${id}`, { headers: { Accept: 'application/vnd.github+json' } })
  if (!res.ok) throw new Error(`Gist not found (${res.status})`)
  const j = (await res.json()) as { files: Record<string, { content: string; truncated?: boolean; raw_url: string }> }
  const out: Record<string, string> = {}
  for (const [name, f] of Object.entries(j.files)) out[name] = f.truncated ? await (await fetch(f.raw_url)).text() : f.content
  return out
}
